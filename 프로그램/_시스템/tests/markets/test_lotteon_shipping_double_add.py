# -*- coding: utf-8 -*-
"""롯데온 배송비 이중가산 회귀 — 2026-07-25 정답지 전수 대조에서 발견.

크롤 실정산(pymtTgtAmt)은 배송비를 포함한다. K열은 상품분(−배송비), N열은 _finalize 가
+고객배송비. 빼는 값이 _finalize 가 더하는 값(`배송비`)과 어긋나면(옛 코드는 `_lo_dvcst`
를 뺐고 크롤 주문은 그게 0) 배송비가 이중 가산돼 정산이 배송비만큼 부풀었다.

라이브 실측(3건): pymtTgtAmt 가 그대로 정답지 '정산예상금액(배송비포함)' 과 같아야 한다.
"""
from lemouton.markets.order_export import _lo_subtract_shipping_once, _finalize_rows


def _n_incl(row):
    """K열(정산예정금액)에서 배송비 뺀 뒤 _finalize 로 N열(배송비포함)을 만든다."""
    _lo_subtract_shipping_once([row])
    _finalize_rows([row])
    return row["정산예정금(배송비포함)"]


def test_크롤주문_배송비_이중가산_안한다():
    """옛 버그: _lo_dvcst=0(크롤주문)이라 빼기 스킵 → _finalize +배송비 이중.

    라이브 실측 2026070413404406: pymtTgtAmt 41,265 = 정답지. 프로그램은 45,265 였다.
    """
    row = {"판매처": "롯데온", "오픈마켓주문번호": "2026070413404406",
           "정산예정금액": 41265, "배송비": 4000, "단가": 41265, "수량": 1,
           "_lo_dvcst": 0}   # 크롤로만 온 주문 = 209 배송비 필드 없음
    assert _n_incl(row) == 41265          # 이중가산이면 45,265


def test_209배송비_있던_기존정상건은_불변():
    """_lo_dvcst==배송비 였던 주문은 빼는 값이 같아 결과가 안 바뀐다."""
    row = {"판매처": "롯데온", "오픈마켓주문번호": "A1",
           "정산예정금액": 50000, "배송비": 3000, "단가": 50000, "수량": 1,
           "_lo_dvcst": 3000}
    assert _n_incl(row) == 50000


def test_무료배송은_그대로():
    row = {"판매처": "롯데온", "오픈마켓주문번호": "A2",
           "정산예정금액": 30000, "배송비": 0, "단가": 30000, "수량": 1}
    assert _n_incl(row) == 30000


def test_배송비를_주문당_1회만_뺀다():
    """다품(2라인) 주문 — 배송비는 배송건당 1회. 과차감 금지."""
    rows = [
        {"판매처": "롯데온", "오픈마켓주문번호": "B1", "정산예정금액": 20000,
         "배송비": 4000, "단가": 20000, "수량": 1},
        {"판매처": "롯데온", "오픈마켓주문번호": "B1", "정산예정금액": 15000,
         "배송비": 0, "단가": 15000, "수량": 1},   # _finalize 가 배송비 0 으로 둔 2번째 라인
    ]
    _lo_subtract_shipping_once(rows)
    assert rows[0]["정산예정금액"] == 16000   # 20000 − 4000
    assert rows[1]["정산예정금액"] == 15000   # 안 건드림


def test_취소진행_change행은_안건드린다():
    row = {"판매처": "롯데온", "오픈마켓주문번호": "C1", "_kind": "change",
           "정산예정금액": 40000, "배송비": 4000}
    _lo_subtract_shipping_once([row])
    assert row["정산예정금액"] == 40000


def test_배송비가_정산보다_크면_안뺀다():
    """음수 정산 날조 금지 — 이상치는 손대지 않는다."""
    row = {"판매처": "롯데온", "오픈마켓주문번호": "D1",
           "정산예정금액": 3000, "배송비": 4000}
    _lo_subtract_shipping_once([row])
    assert row["정산예정금액"] == 3000
