# -*- coding: utf-8 -*-
"""[2026-08-13] 양식 설정 화면의 **열 설명**이 실제 계산과 같은 말을 해야 한다.

🔴 왜 시험까지 만드나 — 설명글이 **사고의 재발 경로**였다.

  `주문내역 > 양식 설정` 은 열마다 계산식을 글로 보여 준다(`orders.py:121` →
  `orders/index.html`). 그 글이 이렇게 적혀 있었다:

      정산예정금액 : "상품정산 + 배송비정산(수수료 차감)"

  그런데 코드는 정반대다 — M열(정산예정금액)에 배송비를 **절대 안 넣는다**
  (`order_export.py:_finalize_rows`). 예전에 스스에서 M 에 배송비 정산을 섞었다가
  N 이 또 더해 **이중 계상 사고**가 났기 때문이다(2026-08-07 · 2,910원 과다 ·
  수수료율 1.32% 오표시). 즉 화면이 **금지된 정의를 광고**하고 있었다.
  다음 사람이 그 글을 믿고 M 에 배송비를 넣으면 그 사고가 그대로 재발한다.

★ 이 파일의 시험은 **글자만 세지 않는다.**
  먼저 `_finalize_rows` 를 실제로 돌려 **코드가 무엇을 하는지 실측**한 다음,
  설명글이 그것과 같은 말을 하는지 본다. 계산이 또 바뀌면 여기서 같이 걸린다.
"""
from lemouton.markets import order_export as OE
from lemouton.markets.order_export import _finalize_rows


def _row(**kw):
    """쿠팡 실측 주문 1100194049219 — 상품 113,924 / 고객배송비 4,000 / 배송비 정산 3,868."""
    base = {'판매처': '쿠팡', '주문일': '2026-07-01', '단가': 128900, '수량': 1,
            '배송비': 4000, '정산예정금액': 113924, '실결제금액': 132900,
            '주문상태': '배송완료'}
    base.update(kw)
    return base


def _desc(col):
    return OE.column_meta(col)['desc']


# ── M열 정산예정금액 — 배송비가 **안** 들어간다 ──────────────────

def test_M열_설명이_배송비는_안_들어간다고_말한다():
    """🔴 종전 설명 「상품정산 + 배송비정산(수수료 차감)」 = 금지된 정의.

    코드가 실제로 M 을 어떻게 두는지 먼저 재고, 설명이 그 말을 하는지 본다.
    「안 들어간다」를 **적어야** 한다 — 안 적으면 다음 사람이 또 넣는다.
    """
    rows = [_row(_ship_settle=3868)]
    _finalize_rows(rows)
    assert rows[0]['정산예정금액'] == 113924, \
        '코드가 M 에 배송비를 넣고 있다 — 이 시험 말고 _finalize_rows 를 봐야 한다'

    d = _desc('정산예정금액')
    assert '배송비' in d, f'배송비 얘기를 아예 안 한다: {d!r}'
    assert any(부정 in d for 부정 in ('안 들어', '제외', '아니')), \
        f'M열이 배송비를 담는다고 읽힌다 — 2026-08-07 이중계상 사고의 재발 경로: {d!r}'


# ── 수수료율 — 분모는 실결제 ──────────────────────────────────

def test_수수료율_설명이_실제_분모와_같은_말을_한다():
    """🔴 종전 설명 「마켓수수료 ÷ 총주문금액」 — 코드는 **실결제**로 나눈다(2026-08-06 정정).

    화면 설명대로 손으로 검산하면 숫자가 안 맞는다 →
    사장님이 「프로그램이 틀렸다」고 오해한다. 실제로 어느 쪽으로 나누는지
    **할인 붙은 행 하나로 재서** 못 박는다.
    """
    # 총주문금액 100,000 (할인 전) ≠ 실결제 80,000 (할인 후) → 분모가 갈린다
    rows = [_row(단가=100000, 수량=1, 배송비=0,
                 실결제금액=80000, 정산예정금액=70000)]
    _finalize_rows(rows)
    실결제기준 = f"{round(10000 / 80000 * 100, 2)}%"      # 12.5%
    총주문기준 = f"{round(10000 / 100000 * 100, 2)}%"     # 10.0%
    assert 실결제기준 != 총주문기준                        # 시험이 헛돌지 않게
    assert rows[0]['수수료율'] == 실결제기준, \
        '코드가 총주문금액으로 나눈다 — 설명이 아니라 코드를 봐야 한다'

    d = _desc('수수료율')
    assert '실결제' in d, f'설명은 아직 정가 기준이라고 말한다: {d!r}'


# ── N열 정산예정금(배송비포함) — 두 갈래 ─────────────────────

def test_N열_설명이_실값과_추정_두_갈래를_다_말한다():
    """🔴 종전 설명 「정산예정금액 + 고객배송비」 — 이제 **배송비 정산 실값**을 더한다.

    실값이 없을 때만 고객배송비 전액으로 떨어진다(추정). 두 갈래를 다 적어야
    「어떤 줄은 3,868, 어떤 줄은 4,000」이 왜 갈리는지 화면만 보고 알 수 있다.
    """
    실값 = [_row(_ship_settle=3868)]
    _finalize_rows(실값)
    assert 실값[0]['정산예정금(배송비포함)'] == 113924 + 3868

    추정 = [_row()]
    _finalize_rows(추정)
    assert 추정[0]['정산예정금(배송비포함)'] == 113924 + 4000

    d = _desc('정산예정금(배송비포함)')
    assert '배송비 정산' in d or '배송비정산' in d, \
        f'아직 고객배송비를 더한다고 말한다: {d!r}'
    assert any(갈래 in d for 갈래 in ('없으면', '추정')), \
        f'실값이 없을 때 고객배송비로 떨어지는 갈래를 안 말한다: {d!r}'


# ── 마켓수수료 — 마켓이 실값을 주면 그걸 쓴다 ────────────────

def test_마켓수수료_설명이_마켓_실값_경로를_빠뜨리지_않는다():
    """설명은 「실결제 − 정산예정금액」 한 갈래만 말하는데, 마켓이 수수료 실값을
    주면(롯데온 SettleCommission) **그 값을 그대로** 쓴다. 그 줄에서만 설명이 틀린다.
    """
    rows = [_row(마켓수수료=9999)]
    _finalize_rows(rows)
    assert rows[0]['마켓수수료'] == 9999, \
        '마켓이 준 실값을 버리고 파생했다'
    assert (132900 - 113924) != 9999                       # 시험이 헛돌지 않게

    d = _desc('마켓수수료')
    assert '마켓' in d and any(말 in d for 말 in ('실값', '주면', '있으면')), \
        f'마켓 실값 경로를 안 말한다: {d!r}'


# ── 설명은 화면까지 나가야 뜻이 있다 ────────────────────────

def test_고친_설명이_양식설정_화면까지_나간다():
    """설명은 `columns_meta()` 로 화면에 넘어간다(`orders.py:121`).
    상수만 고치고 이 통로가 끊기면 화면은 옛 글자 그대로다."""
    meta = OE.columns_meta()
    for col in ('정산예정금액', '수수료율', '정산예정금(배송비포함)', '마켓수수료'):
        assert col in meta, f'{col} 이 양식 설정 화면 목록에서 빠졌다'
        assert meta[col]['desc'] == _desc(col)
