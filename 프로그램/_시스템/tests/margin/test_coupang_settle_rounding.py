# -*- coding: utf-8 -*-
"""[2026-08-13] 쿠팡 정산 추정 — 반올림을 쿠팡과 같게. 건당 1원 과대를 없앤다.

■ 사장님 확정 (2026-08-13)
    「할인가 = 판매가 − 즉시할인 − 쿠폰적용. **정산되는 기준이 되는 금액이 할인가**」

  🔴 인수인계서 §7 은 「기준 = 판매가 × 수량 − 수수료 (**할인가 아님**)」이라고 적혀
    있었는데, 사장님이 맞고 그 문장이 틀렸다. 쿠팡 정산 엑셀 전수로 판정:

        정산금액 = 할인가 − 수수료      → 안 맞는 행 **0**
        정산금액 = 판매액 − 수수료      → 안 맞는 행 **109**

    (인수인계서가 헷갈린 건 **누가 부담하느냐**다. 판매자 부담 쿠폰은 정산에서 빠지고,
     쿠팡 부담 할인은 쿠팡이 메우므로 안 빠진다. 우리 코드는 이미 그렇게 갈라 놨다.)

■ 그런데 반올림이 달랐다 — 건당 1원씩 **우리가 크게** 잡았다

  쿠팡:   수수료 = 반올림(할인가 × 요율)  → 정산 = 할인가 − 수수료
  우리:   정산 = round(할인가 × (1 − 요율))

  파이썬 `round()` 는 **은행가 반올림**이라 `.5` 를 짝수 쪽으로 보낸다.
  엑셀 실측: `할인가 × 11.55%` 가 정확히 `.5` 로 떨어지는 **28행 전부 쿠팡이 올림**
  (내림 0건). 그 자리에서 우리는 정산을 1원 크게 잡아 「받을 돈」이 과대였다.

  재현율: 옛 식 98/138 → 새 식 **124/138**.
  남은 14행은 그 상품의 실제 요율이 11.548~11.549% 라 고정 11.55% 로는 못 맞춘다
  (요율을 아는 상품은 `fee_rate` 로 넘겨 정확히 맞춘다 — 함수가 이미 받는다).
"""
from lemouton.markets.order_export import _cp_estimate_settle


# ── 쿠팡 정산 엑셀 실측값 (MSF_PAYMENT_REVENUE_DETAIL · 2026-08-12) ──
#    (할인가, 쿠팡 판매수수료, 쿠팡 정산금액)
실측 = [
    (59000, 6815, 52185),      # 59,000 × 11.55% = 6,814.5 → 쿠팡 올림
    (65000, 7508, 57492),      # 65,000 × 11.55% = 7,507.5 → 쿠팡 올림
]


def test_반올림_자리에서_쿠팡과_같은_값이_나온다():
    """🔴 `.5` 로 떨어지는 자리 — 여기가 1원씩 어긋나던 곳이다."""
    for 할인가, 수수료, 정산 in 실측:
        got = _cp_estimate_settle(할인가, 1, 0)
        assert got == 정산, (
            f'할인가 {할인가:,}: 쿠팡 {정산:,} 인데 우리는 {got:,} '
            f'({got - 정산:+}원 — 은행가 반올림 탓)')


def test_수수료를_먼저_반올림한다():
    """정산 = 할인가 − 반올림(할인가 × 요율). 곱셈을 한 번에 하면 자리가 어긋난다."""
    for 할인가, 수수료, 정산 in 실측:
        assert 할인가 - 수수료 == 정산            # 엑셀 항등식 확인(시험이 헛돌지 않게)
        assert _cp_estimate_settle(할인가, 1, 0) == 할인가 - 수수료


def test_판매자부담할인은_기준에서_뺀다():
    """사장님 확정 — 정산 기준은 **할인가**(판매가 − 즉시할인 − 쿠폰)."""
    할인_없음 = _cp_estimate_settle(100000, 1, 0, seller_dc=0)
    할인_있음 = _cp_estimate_settle(100000, 1, 0, seller_dc=10000)
    assert 할인_있음 < 할인_없음
    # 90,000 × 11.55% = 10,395 → 정산 79,605
    assert 할인_있음 == 90000 - 10395


def test_쿠팡부담할인은_안_뺀다():
    """쿠팡이 메우는 할인까지 빼면 「받을 돈」이 실제보다 작아진다.

    함수는 `seller_dc`(판매자 부담)만 받는다 — 호출부가 쿠팡부담분을 안 넘기는 것이
    규약이고, 그 규약을 여기서 못 박는다.
    """
    import inspect
    src = inspect.getsource(_cp_estimate_settle)
    assert 'seller_dc' in inspect.signature(_cp_estimate_settle).parameters
    assert '쿠팡지원할인' in src or '쿠팡이 보전' in src


def test_요율을_아는_상품은_그_요율로_정확히():
    """정산 확정분에서 배운 **부가세 포함** 실효 요율은 그대로 쓴다(1.1 을 또 곱하지 않는다)."""
    # 88,900 × 11.549% = 10,267.06 → 반올림 10,267 → 정산 78,633 (엑셀 실측)
    got = _cp_estimate_settle(88900, 1, 0, fee_rate=0.11549)
    assert got == 88900 - 10267


# ── 사장님이 준 쿠팡 시험 결과 그대로 ─────────────────────────

def test_사장님_식_그대로_센다():
    """수수료 = 반올림( 버림(기준 × 요율(VAT별도)) × 1.1 ).

    🔴 순서가 중요하다. 11.55% = 10.5% × 1.1 이지만 **버림 자리가 달라** 값이 갈린다.
       88,900: 버림(88,900×10.5%)=9,334 → ×1.1=10,267.4 → 10,267  (쿠팡 실제)
               한 번에 ×11.55% 면 10,267.95 → 10,268 로 **1원 크다**
    """
    from lemouton.markets.order_export import cp_fee
    assert cp_fee(88900) == 10267
    assert cp_fee(59000) == 6815          # 버림(6,195)×1.1 = 6,814.5 → 올림
    assert _cp_estimate_settle(88900, 1, 0) == 88900 - 10267


def test_배송료는_요율이_따로다():
    """배송료 행은 3.0%(VAT별도) — 상품과 같은 요율로 물리면 안 된다."""
    from lemouton.markets.order_export import (
        CP_SHIP_FEE_RATE_EX_VAT, cp_fee,
    )
    # 버림(4,000 × 3%) = 120 → ×1.1 = 132 → 정산 3,868 (사장님 시험 결과·엑셀 실측)
    assert cp_fee(4000, CP_SHIP_FEE_RATE_EX_VAT) == 132


def test_단가가_없으면_지어내지_않는다():
    assert _cp_estimate_settle(None, 1, 0) == ''
    assert _cp_estimate_settle('', 1, 0) == ''


def test_엑셀_전수가_한_행도_안_틀린다():
    """🔴 낱개 몇 건이 아니라 **전수**로 못 박는다 — 상품 299 + 배송료 156 = 455행.

    요율은 엑셀의 「서비스이용율(%,VAT별도)」 열이 행마다 알려 준다(상품 10.5 / 배송료 3.0 / 0).
    쿠팡 정산 엑셀이 없는 환경(CI)에서는 건너뛴다 — 사장님 PC 의 다운로드 파일이다.
    """
    import glob

    import pytest

    from lemouton.markets.order_export import cp_fee
    fs = sorted(glob.glob(
        'C:/Users/seung/Downloads/MSF_PAYMENT_REVENUE_DETAIL-2026-08-12*.xlsx'))
    if not fs:
        pytest.skip('쿠팡 정산 엑셀이 없는 환경 — 사장님 PC 의 다운로드 파일')
    import pandas as pd
    d = (pd.concat([pd.read_excel(f) for f in fs], ignore_index=True)
         .drop_duplicates())
    배송 = d['옵션 ID'].astype(str).str.contains('기본배송료', na=False)
    틀림 = []
    for 이름, t in (('상품', d[~배송]), ('배송료', d[배송])):
        for _, r in t.iterrows():
            기준 = int(r['판매액']) - (int(r['판매자 할인쿠폰(A+B)'])
                                      if 이름 == '상품' else 0)
            요율 = float(r['서비스이용율(%,VAT별도)']) / 100.0
            f = cp_fee(기준, 요율)
            if f != int(r['판매수수료']) or 기준 - f != int(r['정산금액']):
                틀림.append((이름, 기준, 요율, f, int(r['판매수수료'])))
    assert 틀림 == [], f'{len(틀림)}행이 쿠팡 값과 다르다 (앞 3건): {틀림[:3]}'
